def _stage(
    stage_id: str,
    title: str,
    role: str,
    action: str,
    complete_when: dict[str, Any] | None = None,
    stale_after_minutes: int | None = None,
) -> dict[str, Any]:
    return {
        "id": stage_id,
        "title": title,
        "action": action,
        "role": role,
        "complete_when": complete_when,
        "stale_after_minutes": stale_after_minutes,
    }


def _power(*, above: float | None = None, below: float | None = None, hold: int) -> dict[str, Any]:
    return {"entity_id": "", "above": above, "below": below, "state": None, "for_seconds": hold}


def _task(
    title: str,
    icon: str,
    scene: str,
    schedule: dict[str, Any],
    on_missed: str,
    stages: list[dict[str, Any]],
    grace_hours: int = 24,
) -> dict[str, Any]:
    return {
        "title": title,
        "icon": icon,
        "color": None,
        "look": None,
        "notes": None,
        "assignee": None,
        "enabled": True,
        "schedule": schedule,
        "on_missed": on_missed,
        "scene": scene,
        "stages": stages,
        "clean_for_minutes": 720,
        "grace_hours": grace_hours,
    }


